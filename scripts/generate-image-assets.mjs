#!/usr/bin/env node
/**
 * Turns a Studio Asset Manager export (Copy → Copy Info) into a typed module.
 *
 *   npm run assets:images
 *
 * Input:  assets/ui/images.csv   (columns: Name, Asset ID, Asset Type, Date Modified, ...)
 * Output: src/shared/assets/images.ts
 *
 * Names become identifiers ("Wheel&Woe" → WheelAndWoe). When the same name was
 * uploaded more than once, every copy is kept with a _v1, _v2… suffix in upload
 * order, so nothing is silently dropped. Rename the files in Asset Manager to
 * get clean keys.
 */
import { readFileSync, writeFileSync } from "node:fs";

const INPUT = "assets/ui/images.csv";
const OUTPUT = "src/shared/assets/images.ts";

/** Minimal CSV parser that handles quoted fields. */
function parseCsv(text) {
	const rows = [];
	for (const line of text.split(/\r?\n/)) {
		if (line.trim() === "") continue;
		const cells = [];
		let cell = "";
		let quoted = false;
		for (let i = 0; i < line.length; i++) {
			const ch = line[i];
			if (quoted) {
				if (ch === '"' && line[i + 1] === '"') (cell += '"'), i++;
				else if (ch === '"') quoted = false;
				else cell += ch;
			} else if (ch === '"') quoted = true;
			else if (ch === ",") cells.push(cell), (cell = "");
			else cell += ch;
		}
		cells.push(cell);
		rows.push(cells);
	}
	return rows;
}

function toIdentifier(name) {
	const words = name
		.replace(/&/g, " And ")
		.split(/[^A-Za-z0-9]+/)
		.filter(Boolean)
		.map((w) => w[0].toUpperCase() + w.slice(1));
	let id = words.join("") || "Image";
	if (/^[0-9]/.test(id)) id = `Image${id}`;
	return id;
}

const [header, ...rows] = parseCsv(readFileSync(INPUT, "utf8"));
const col = (title) => {
	const index = header.findIndex((h) => h.trim().toLowerCase() === title.toLowerCase());
	if (index === -1) throw new Error(`${INPUT}: missing "${title}" column`);
	return index;
};
const NAME = col("Name");
const ID = col("Asset ID");
const TYPE = col("Asset Type");
const DATE = col("Date Modified");

const images = rows
	.filter((r) => r[TYPE]?.trim() === "Image")
	.map((r) => ({ name: r[NAME].trim(), id: r[ID].trim(), date: Number(r[DATE]) }))
	.filter((img) => /^\d+$/.test(img.id));

// Group same-named uploads, order each group by upload date.
const groups = new Map();
for (const img of images) {
	const key = toIdentifier(img.name);
	if (!groups.has(key)) groups.set(key, []);
	groups.get(key).push(img);
}

const entries = [];
const duplicates = [];
for (const [key, group] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
	group.sort((a, b) => a.date - b.date);
	if (group.length > 1) duplicates.push(key);
	group.forEach((img, i) => entries.push({ ...img, key: group.length > 1 ? `${key}_v${i + 1}` : key }));
}

const day = (ms) => (Number.isFinite(ms) ? new Date(ms).toISOString().slice(0, 10) : "unknown");
const lines = [
	"// Generated by scripts/generate-image-assets.mjs from assets/ui/images.csv. Do not edit by hand:",
	"// update the CSV (Asset Manager → Copy → Copy Info) and run `npm run assets:images`.",
	"",
	"/** UI image asset ids, keyed by their Asset Manager name. */",
	"export const Images = {",
	...entries.map((e) => `\t/** "${e.name}", modified ${day(e.date)} */\n\t${e.key}: "rbxassetid://${e.id}",`),
	"} as const;",
	"",
	"export type ImageName = keyof typeof Images;",
	"",
];
if (duplicates.length > 0) {
	lines.push(
		"/**",
		" * Names uploaded more than once; each copy is kept as _v1, _v2… (oldest first).",
		" * Pick the right one, then delete or rename the others in Asset Manager.",
		" */",
		`export const DUPLICATE_IMAGE_NAMES = [${duplicates.map((d) => `"${d}"`).join(", ")}] as const;`,
		"",
	);
}
writeFileSync(OUTPUT, lines.join("\n"));
console.log(`${OUTPUT}: ${entries.length} images${duplicates.length ? `, duplicates: ${duplicates.join(", ")}` : ""}`);
